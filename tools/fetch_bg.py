"""Page header photos from Wikimedia Commons -> assets/bg/<key>.webp + assets/bg/bg.js (credits).

    python3 tools/fetch_bg.py tools/bg_photos.json

tools/bg_photos.json maps a page key to a Commons file and a caption:
    {"prov-jambi": {"file": "File:Muaro Jambi Temple ... .jpg", "t": "Candi Muaro Jambi"}, ...}
Keys: prov-<province slug>, plant-indarung, moda-darat, moda-laut, moda-kontainer (see pageBgKey in app.js).
Only freely licensed files are accepted (CC0 / public domain / CC BY / CC BY-SA); author and licence are read from
Commons and shown on the site (#/kredit), as the licences require. Images are cropped to a wide band and saved as
WebP (~1600 px, quality 70) so they stay light on phones. Needs Pillow and network access to *.wikimedia.org.
"""
import io, json, os, re, sys, time, urllib.parse, urllib.request

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "bg")
UA = {"User-Agent": "logistik-sp-dashboard/1.0 (internal company dashboard)"}
OK = re.compile(r"^(CC0|Public domain|PD|CC BY(-SA)? ?\d)", re.I)
W, RATIO = 1600, 3.0          # output width, width/height of the header band


def get(url):
    for i in range(6):
        try:
            time.sleep(3)
            return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60).read()
        except urllib.error.HTTPError as e:
            if e.code != 429:
                raise
            time.sleep(60 * (i + 1))
    raise SystemExit("Wikimedia membatasi permintaan (429). Coba lagi nanti.")


def info(title):
    q = urllib.parse.urlencode({"action": "query", "format": "json", "titles": title, "prop": "imageinfo",
                                "iiprop": "url|size|extmetadata", "iiurlwidth": W * 1.25})
    page = next(iter(json.loads(get("https://commons.wikimedia.org/w/api.php?" + q))["query"]["pages"].values()))
    ii = page["imageinfo"][0]
    md = ii.get("extmetadata", {})
    clean = lambda k: re.sub(r"\s+", " ", re.sub("<[^>]+>", "", md.get(k, {}).get("value", ""))).strip()
    return ii, clean("LicenseShortName"), clean("Artist") or "tidak diketahui"


def main():
    sel = json.load(open(sys.argv[1], encoding="utf-8"))
    os.makedirs(OUT, exist_ok=True)
    credits = {}
    for key, s in sel.items():
        ii, lic, artist = info(s["file"])
        if not OK.match(lic):
            print(f"  LEWATI {key}: lisensi {lic!r} tidak bebas")
            continue
        im = Image.open(io.BytesIO(get(ii.get("thumburl") or ii["url"]))).convert("RGB")
        w, h = im.size
        th = int(w / RATIO)
        if th < h:   # crop a centred band (focus slightly above the middle, where landmarks usually are)
            top = max(0, min(h - th, int(h * s.get("focus", 0.42)) - th // 2))
            im = im.crop((0, top, w, top + th))
        im = im.resize((W, int(W * im.size[1] / im.size[0])), Image.LANCZOS)
        fn = key + ".webp"
        im.save(os.path.join(OUT, fn), "WEBP", quality=70, method=6)
        credits[key] = {"f": fn, "t": s["t"], "a": artist[:80], "l": lic, "u": ii["descriptionurl"]}
        print(f"  {key}: {fn} {os.path.getsize(os.path.join(OUT, fn)) // 1024} KB · {lic} · {artist[:40]}")
    with open(os.path.join(OUT, "bg.js"), "w", encoding="utf-8") as f:
        f.write("/* Page header photos (see applyPageBg in app.js). Generated by tools/fetch_bg.py; credits at #/kredit. */\n")
        f.write("window.BG = " + json.dumps(credits, ensure_ascii=False, indent=1) + ";\n")
    print(f"{len(credits)} foto -> assets/bg/")


if __name__ == "__main__":
    main()
